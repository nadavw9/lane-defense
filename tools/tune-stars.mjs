// Star targets per level from simulated WINNING runs (average skill, the tuning reference profile):
//   one   = the goal's own points (goal cars x POINTS.car): every win has at least that, so the
//           bar's first star is always lit by the time the level is won
//   two   = 35th percentile
//   (levels won 95%+ of the time, the tutorial: three = halfway from the goal's points to the 20th
//    percentile, two = a quarter of the way, so a first-time player's win is three stars)
//   three = 75th percentile  -> about a quarter of an average player's wins earn three stars,
//                               more for a good player, so three stars is always reachable.
// Rounded to 25 points and kept strictly rising.
//   node tools/tune-stars.mjs 1-200 [runs=300] [--write]   (writes src/game/starTargets.js)
import { LevelManager, LEVEL_COUNT } from '../src/game/LevelManager.js';
import { SimulationRunner } from '../src/simulation/SimulationRunner.js';
import { POINTS } from '../src/game/score.js';

const [range = `1-${LEVEL_COUNT}`, runsArg = '300'] = process.argv.slice(2).filter(a => !a.startsWith('--'));
const [lo, hi = lo] = range.split('-').map(Number);
const RUNS = Number(runsArg);
const r25 = (x) => Math.round(x / 25) * 25;

const out = {};
for (let id = lo; id <= hi; id++) {
  const lm = new LevelManager(); lm.goToLevel(id);
  const runner = SimulationRunner.fromLevel(lm.current, { skill: 'average' });
  const wins = [];
  for (let s = 1; s <= RUNS; s++) { const r = runner.runLevel(s); if (r.won) wins.push(r.score); }
  wins.sort((a, b) => a - b);
  const q = (p) => wins[Math.floor(p * (wins.length - 1))];
  const goal = (lm.current.goals ?? []).reduce((a, g) => a + g.count, 0);
  let one, two, three;
  // Levels nearly everyone wins (the tutorial) score almost the same every time: their targets come
  // from lower percentiles so a first-time player earns three stars there without a perfect game.
  const easy = wins.length >= 0.95 * RUNS;
  if (easy) {   // halfway from the goal's points to a typical (20th percentile) win: a win with a
                 // broken combo or two is still three stars
    const typical = q(0.2), base = goal * POINTS.car;
    three = r25(base + (typical - base) * 0.5); two = r25(base + (typical - base) * 0.25);
  } else if (wins.length >= 20) { two = r25(q(0.35)); three = r25(q(0.75)); }
  else {   // too few wins to read percentiles: derive from the goal, like starTargetsFor's fallback
    two = r25(goal * POINTS.car * 1.25); three = r25(goal * POINTS.car * 1.5);
  }
  one = Math.max(POINTS.car, goal * POINTS.car);
  two = Math.max(two, one + 25); three = Math.max(three, two + 25);
  out[id] = [one, two, three];
  console.error(`L${id}: wins ${wins.length}/${RUNS} -> ${out[id].join(' / ')}`);
}
console.log(JSON.stringify(out));
if (process.argv.includes('--write')) {
  const { STAR_TARGETS } = await import('../src/game/starTargets.js');
  const merged = { ...STAR_TARGETS, ...out };
  const body = Object.entries(merged).sort((a, b) => a[0] - b[0]).map(([id, t]) => `  ${id}: [${t.join(', ')}],`).join('\n');
  const { writeFileSync } = await import('node:fs');
  writeFileSync(new URL('../src/game/starTargets.js', import.meta.url),
    `// GENERATED by \`node tools/tune-stars.mjs 1-200 --write\`. Do not hand-edit.\n// [one, two, three] score targets per level, from simulated winning runs (average skill).\nexport const STAR_TARGETS = {\n${body}\n};\n`);
  console.error('wrote src/game/starTargets.js');
}
